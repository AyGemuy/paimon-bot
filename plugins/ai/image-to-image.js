import axios from "axios";
import {
  upload
} from "../../lib/upload.js";
import {
  simpleQuoted
} from "../../lib/quoted.js";
export default {
  name: "imagetoimage",
  aliases: ["imagetoimage", "i2i", "t2i"],
  description: "AI Image Generator & Editor (T2I / I2I) via Image-to-Image API",
  category: "AI",
  limit: true,
  example: "imagetoimage <prompt> [--state <token>] atau reply gambar dengan caption imagetoimage <prompt>",
  execute: async (sock, ctx, msg) => {
    try {
      let text = ctx.args?.join(" ")?.trim() || "";
      if (!text && ctx.text) {
        const raw = ctx.text.trim();
        const firstWord = raw.split(/\s+/)[0].toLowerCase();
        if (firstWord.endsWith("imagetoimage") || firstWord.endsWith("i2i") || firstWord.endsWith("t2i")) {
          text = raw.slice(firstWord.length).trim();
        }
      }
      const isMedia = ctx.isMedia || ctx.quoted?.isMedia;
      const prefix = ctx.prefix || ".";
      const botName = global.bot?.name || "WudysoftBot";
      const quotedMsg = typeof simpleQuoted === "function" ? simpleQuoted(ctx) : msg;
      if (!text && !isMedia) {
        return ctx.reply(`🎨 *IMAGE TO IMAGE AI*\n\n` + `• *Text-to-Image (T2I):*\n` + `  👉 \`${prefix}imagetoimage cute cyberpunk cat\`\n\n` + `• *Image-to-Image (I2I):*\n` + `  👉 Kirim/Reply gambar dengan: \`${prefix}imagetoimage add hat\`\n\n` + `• *Dengan State (Lanjutan Edit):*\n` + `  👉 \`${prefix}imagetoimage change background --state <token_state>\``);
      }
      await ctx.react("⏳");
      let prompt = text;
      let state = "";
      if (/--state\s+([^\s]+)/i.test(prompt)) {
        const match = prompt.match(/--state\s+([^\s]+)/i);
        if (match) state = match[1];
        prompt = prompt.replace(/--state\s+[^\s]+/gi, "").trim();
      }
      const body = {
        prompt: prompt || "enhance quality, masterpiece, 4k ultra detailed"
      };
      let imageUrl = "";
      if (isMedia) {
        const buffer = await ctx.download();
        if (buffer && Buffer.isBuffer(buffer)) {
          const uploadRes = await upload(buffer);
          if (uploadRes?.status && uploadRes?.url) {
            imageUrl = uploadRes.url;
            body.image = imageUrl;
          } else {
            await ctx.react("❌");
            return ctx.reply(`❌ Gagal mengunggah gambar: ${uploadRes?.message || "Server upload error"}`);
          }
        }
      }
      if (state) {
        body.state = state;
      }
      const {
        data
      } = await axios.post("https://wudysoft.my.id/api/ai/image-to-image", body, {
        headers: {
          "Content-Type": "application/json",
          "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"
        },
        timeout: 6e4
      });
      if (!data || !data.status || !data.result) {
        await ctx.react("❌");
        return ctx.reply(`❌ Gagal memproses gambar: ${data?.message || "Respon server tidak valid."}`);
      }
      const resultImageUrl = data.result?.generate_url || data.result?.url || (typeof data.result === "string" ? data.result : null);
      const returnedState = data.result?.state || data.state || "";
      const mode = imageUrl ? "IMAGE-TO-IMAGE" : "TEXT-TO-IMAGE";
      if (!resultImageUrl || typeof resultImageUrl !== "string") {
        await ctx.react("❌");
        return ctx.reply("❌ Gambar hasil tidak ditemukan pada respon API.");
      }
      const bodyText = `🎨 *IMAGE TO IMAGE COMPLETED*\n\n` + `📝 *Prompt:* ${prompt || "-"}\n` + `🎭 *Mode:* \`${mode}\`\n\n` + `_💡 Klik tombol copy di bawah untuk melanjutkan modifikasi gambar ini._`;
      const footerText = `${botName} • Image-to-Image AI`;
      const buttons = [];
      if (returnedState) {
        const nextCommand = `${prefix}imagetoimage <tulis_prompt_edit_lanjutan> --state ${returnedState}`;
        buttons.push({
          name: "cta_copy",
          display_text: "📋 Salin Lanjutan Edit",
          copy_code: nextCommand
        }, {
          name: "cta_copy",
          display_text: "🔑 Salin State Token",
          copy_code: returnedState
        });
      }
      if (typeof ctx.sendCta === "function") {
        await ctx.sendCta(bodyText, footerText, buttons, {
          title: `乂 I2I AI - ${mode} 乂`,
          subtitle: "Generated by Image-to-Image AI",
          media: resultImageUrl,
          quoted: quotedMsg
        });
      } else {
        await sock.sendMessage(ctx.id, {
          image: {
            url: resultImageUrl
          },
          caption: bodyText
        }, {
          quoted: quotedMsg
        });
      }
      await ctx.react("✅");
    } catch (error) {
      await ctx.react("❌");
      const errMsg = error.response?.data?.message || error.response?.data?.error || (typeof error.response?.data === "string" ? error.response.data : null) || error.message;
      ctx.reply(`❌ Terjadi kesalahan: ${errMsg}`);
    }
  }
};